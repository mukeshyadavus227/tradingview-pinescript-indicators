#!/usr/bin/env python3
"""
Generate the ADS2 sector-map block (ticker -> Select Sector SPDR code) from
sector_map/spdr_holdings_*.txt and write it between the <sector-map:begin> /
<sector-map:end> markers in ../ads2_daily_scanner.pine.

Why a ticker map: the Pine Screener leaves syminfo.sector empty, so ADS2 v2.2's
sector lookup (keyed on syminfo.sector) resolved nothing in the Screener. syminfo.ticker
is supplied there, so ADS2 v2.3 keys the lookup on it.

  python build_sector_map.py            # rewrite the block in place
  python build_sector_map.py --check    # exit 1 if the Pine block is out of date
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PINE = HERE.parent / "ads2_daily_scanner.pine"
SRC = sorted((HERE / "sector_map").glob("spdr_holdings_*.txt"))[-1]
ETFS = ["XLK", "XLF", "XLV", "XLP", "XLY", "XLI", "XLE", "XLB", "XLU", "XLC"]   # codes 1..10, the column's encoding
TICKER = re.compile(r"^[A-Z]{1,5}(\.[A-Z])?$")
BEGIN, END = "// <sector-map:begin>", "// <sector-map:end>"
WRAP = 104


def load():
    lists, seen = {}, {}
    for line in SRC.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        code, etf, *tickers = line.split()
        code = int(code)
        assert ETFS[code - 1] == etf, f"code {code} must be {ETFS[code - 1]}, got {etf}"
        for t in tickers:
            assert TICKER.match(t), f"{etf}: not an equity ticker: {t!r}"
            assert t not in seen, f"{t} listed in both {seen[t]} and {etf}"
            seen[t] = etf
        lists[etf] = tickers
    assert list(lists) == ETFS, f"need exactly {ETFS}, got {list(lists)}"
    return lists


def block(lists):
    n = sum(len(v) for v in lists.values())
    date = SRC.stem.split("_")[-1]
    out = [BEGIN + " generated by research/build_sector_map.py from " + SRC.name + " — do not edit by hand",
           f"// Full holdings of the ten Select Sector SPDR ETFs, holdings date {date} (Zacks Investment",
           f"// Research), {n} US tickers. XLRE has no code here, so REITs resolve to unknown (code 0)."]
    for etf in ETFS:
        body = "|" + "|".join(lists[etf]) + "|"
        head = f'const string SEC_{etf} = '
        chunks, cur = [], ""
        for tok in body.split("|")[1:-1]:                       # wrap on ticker boundaries
            piece = tok + "|"
            if len(head) + len(cur) + len(piece) + 2 > WRAP and cur:
                chunks.append(cur); cur = ""
            cur += piece
        chunks.append(cur)
        chunks[0] = "|" + chunks[0]
        # operator at the end of the line, continuation indented 5 spaces (Pine: not a multiple of 4)
        quoted = [f'"{c}"' for c in chunks]
        lines = [head + quoted[0] + (" +" if len(quoted) > 1 else "")]
        lines += [f"     {q}" + (" +" if k < len(quoted) - 1 else "") for k, q in enumerate(quoted[1:], start=1)]
        out.append(f"// {etf}: {len(lists[etf])}")
        out.extend(lines)
    out.append(END)
    return "\n".join(out)


def main():
    lists = load()
    new = block(lists)
    src = PINE.read_text()
    i, j = src.index(BEGIN), src.index(END) + len(END)
    cur = src[i:j]
    if "--check" in sys.argv:
        ok = cur == new
        print("sector map block is current" if ok else "sector map block is OUT OF DATE")
        sys.exit(0 if ok else 1)
    PINE.write_text(src[:i] + new + src[j:])
    print(f"wrote {sum(len(v) for v in lists.values())} tickers into {PINE.name}: " +
          ", ".join(f"{e} {len(lists[e])}" for e in ETFS))


if __name__ == "__main__":
    main()
